package com.xuanchen.generator.dialect;

import com.xuanchen.common.exception.BusinessException;
import com.xuanchen.generator.gentable.entity.GenTable;
import com.xuanchen.generator.gentable.entity.GenTableColumn;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * PostgreSQL 方言实现。
 * <p>
 * 约定：使用连接库的 public schema（PG 的库名与 schema 是两级概念，这里不做 schema 选择）。
 * 元数据类型统一归一化为 MySQL 风格，便于上层复用 Java 类型映射与控件推断；
 * 建表时再映射回 PG 类型，自增列使用 {@code GENERATED BY DEFAULT AS IDENTITY}。
 *
 * @author XuanChen
 * @date 2026-10-19
 */
public class PostgresDialect implements DatabaseDialect {

    private static final Pattern IDENTIFIER_PATTERN = Pattern.compile("[A-Za-z_][A-Za-z0-9_]{0,63}");

    /** 归一化后的类型白名单（与 MySQL 侧保持同一套语义） */
    private static final Set<String> ALLOWED_TYPES = Set.of(
            "tinyint", "smallint", "mediumint", "int", "integer", "bigint",
            "decimal", "numeric", "float", "double",
            "char", "varchar", "tinytext", "text", "mediumtext", "longtext",
            "binary", "varbinary", "blob", "mediumblob", "longblob",
            "date", "datetime", "timestamp", "time", "year",
            "bit", "bool", "boolean", "json");

    private static final Set<String> LENGTH_TYPES = Set.of("char", "varchar", "binary", "varbinary");
    private static final Set<String> SCALE_TYPES = Set.of("decimal", "numeric");
    private static final Set<String> INT_TYPES = Set.of("tinyint", "smallint", "mediumint", "int", "integer", "bigint");
    private static final Set<String> NUMERIC_TYPES = Set.of(
            "tinyint", "smallint", "mediumint", "int", "integer", "bigint",
            "decimal", "numeric", "float", "double", "bit", "bool", "boolean");
    private static final int MAX_LENGTH = 65535;
    private static final int MAX_SCALE = 30;
    private static final int MAX_NUMERIC_PRECISION = 65;

    @Override
    public String key() {
        return "postgresql";
    }

    @Override
    public String buildUrl(String host, String port, String dbName) {
        return "jdbc:postgresql://" + host + ":" + port + "/" + dbName + "?currentSchema=public";
    }

    @Override
    public List<Map<String, Object>> listTables(Connection conn, String dbName) throws SQLException {
        List<Map<String, Object>> list = new ArrayList<>();
        String sql = "SELECT t.table_name, "
                + "obj_description((quote_ident(t.table_schema)||'.'||quote_ident(t.table_name))::regclass) AS table_comment "
                + "FROM information_schema.tables t "
                + "WHERE t.table_schema = 'public' AND t.table_type = 'BASE TABLE' ORDER BY t.table_name";
        try (PreparedStatement ps = conn.prepareStatement(sql); ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                Map<String, Object> map = new HashMap<>();
                map.put("tableName", rs.getString("table_name"));
                map.put("tableComment", rs.getString("table_comment"));
                list.add(map);
            }
        }
        return list;
    }

    @Override
    public List<Map<String, Object>> listColumns(Connection conn, String dbName, String tableName) throws SQLException {
        Set<String> pkColumns = listPrimaryKeys(conn, tableName);
        List<Map<String, Object>> list = new ArrayList<>();
        String sql = "SELECT c.column_name, c.data_type, c.character_maximum_length, c.numeric_scale, "
                + "c.is_nullable, c.column_default, "
                + "col_description((quote_ident(c.table_schema)||'.'||quote_ident(c.table_name))::regclass, c.ordinal_position) AS column_comment "
                + "FROM information_schema.columns c "
                + "WHERE c.table_schema = 'public' AND c.table_name = ? ORDER BY c.ordinal_position";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, tableName);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String columnName = rs.getString("column_name");
                    Map<String, Object> map = new HashMap<>();
                    map.put("columnName", columnName);
                    map.put("columnComment", rs.getString("column_comment"));
                    map.put("columnType", normalizeMetaType(rs.getString("data_type")));
                    map.put("columnLength", rs.getString("character_maximum_length"));
                    map.put("columnScale", rs.getString("numeric_scale"));
                    map.put("columnDefault", rs.getString("column_default"));
                    map.put("columnIsPk", pkColumns.contains(columnName));
                    map.put("columnIsNullable", "YES".equalsIgnoreCase(rs.getString("is_nullable")));
                    map.put("extra", "");
                    list.add(map);
                }
            }
        }
        return list;
    }

    /**
     * 查询主键列集合（PG 的 information_schema.columns 不带主键信息，需查约束）。
     */
    private Set<String> listPrimaryKeys(Connection conn, String tableName) throws SQLException {
        Set<String> pk = new HashSet<>();
        String sql = "SELECT kcu.column_name FROM information_schema.table_constraints tc "
                + "JOIN information_schema.key_column_usage kcu "
                + "ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema "
                + "WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = 'public' AND tc.table_name = ?";
        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, tableName);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    pk.add(rs.getString("column_name"));
                }
            }
        }
        return pk;
    }

    @Override
    public List<String> buildCreateTable(GenTable table, List<GenTableColumn> columns) {
        String tableName = table.getTableName();
        if (tableName == null || !IDENTIFIER_PATTERN.matcher(tableName).matches()) {
            throw new BusinessException(400, "表名仅允许字母、数字、下划线，且必须以字母或下划线开头（最长 64 位）");
        }
        if (columns == null || columns.isEmpty()) {
            throw new BusinessException(400, "已选择「是否创建表 = 是」，但没有配置任何字段，"
                    + "请先在「数据库表配置」页签添加字段（至少包含一个主键字段）");
        }

        List<String> pkColumns = new ArrayList<>();
        for (GenTableColumn column : columns) {
            String columnName = column.getColumnName();
            if (columnName == null || !IDENTIFIER_PATTERN.matcher(columnName).matches()) {
                throw new BusinessException(400, "字段名「" + columnName
                        + "」不合法：仅允许字母、数字、下划线，且必须以字母或下划线开头");
            }
            if (isTrue(column.getColumnIsPk())) {
                pkColumns.add(columnName);
            }
        }
        if (pkColumns.isEmpty()) {
            throw new BusinessException(400, "建表至少需要一个主键字段，请在「数据库表配置」中勾选一个字段的「是否主键」");
        }

        List<String> definitions = new ArrayList<>();
        List<String> comments = new ArrayList<>();
        for (GenTableColumn column : columns) {
            boolean pk = isTrue(column.getColumnIsPk());
            boolean identity = pkColumns.size() == 1 && pk;
            definitions.add(definition(column, pk, identity));
            String comment = column.getColumnComment();
            comments.add("COMMENT ON COLUMN " + quote(tableName) + "." + quote(column.getColumnName())
                    + " IS '" + escape(comment == null || comment.isBlank() ? column.getColumnName() : comment) + "'");
        }
        definitions.add("PRIMARY KEY (" + quoteAll(pkColumns) + ")");

        List<String> sqls = new ArrayList<>();
        StringBuilder ddl = new StringBuilder();
        ddl.append("CREATE TABLE IF NOT EXISTS ").append(quote(tableName)).append(" (\n  ")
                .append(String.join(",\n  ", definitions)).append("\n)");
        sqls.add(ddl.toString());

        String tableComment = table.getTableComment();
        if (tableComment != null && !tableComment.isBlank()) {
            sqls.add("COMMENT ON TABLE " + quote(tableName) + " IS '" + escape(tableComment) + "'");
        }
        sqls.addAll(comments);
        return sqls;
    }

    private String definition(GenTableColumn column, boolean pk, boolean identity) {
        // 建表时的类型来自字段配置（已是 MySQL 风格白名单值），不能走元数据归一化
        String type = column.getColumnType() == null ? "" : column.getColumnType().trim().toLowerCase(Locale.ROOT);
        if (!ALLOWED_TYPES.contains(type)) {
            throw new BusinessException(400, "字段类型「" + column.getColumnType() + "」不受支持，请从下拉框中选择");
        }
        StringBuilder sb = new StringBuilder();
        sb.append(quote(column.getColumnName())).append(' ')
                .append(pgTypeExpr(type, column));
        sb.append(pk ? " NOT NULL" : (isTrue(column.getColumnIsNullable()) ? " NULL" : " NOT NULL"));

        String defaultValue = defaultValueExpr(type, column.getColumnDefault(), pk);
        if (defaultValue != null) {
            sb.append(" DEFAULT ").append(defaultValue);
        }
        if (identity && INT_TYPES.contains(type) && defaultValue == null) {
            sb.append(" GENERATED BY DEFAULT AS IDENTITY");
        }
        return sb.toString();
    }

    /**
     * 归一化类型 --> PostgreSQL 类型表达式（含长度/精度）。
     */
    private String pgTypeExpr(String type, GenTableColumn column) {
        if (SCALE_TYPES.contains(type)) {
            Integer length = column.getColumnLength();
            Integer scale = column.getColumnScale();
            if (length != null && length > 0) {
                StringBuilder sb = new StringBuilder("numeric(").append(Math.min(length, MAX_NUMERIC_PRECISION));
                if (scale != null && scale > 0) {
                    sb.append(',').append(Math.min(scale, MAX_SCALE));
                }
                return sb.append(')').toString();
            }
            return "numeric";
        }
        if (LENGTH_TYPES.contains(type)) {
            Integer length = column.getColumnLength();
            if (length == null || length <= 0) {
                throw new BusinessException(400, "字段「" + column.getColumnName() + "」类型为 " + type
                        + "，必须填写字段长度");
            }
            String pgType = "binary".equals(type) || "varbinary".equals(type) ? "bytea" : type;
            return "bytea".equals(pgType) ? "bytea" : pgType + "(" + Math.min(length, MAX_LENGTH) + ")";
        }
        return pgTypeExpr(type);
    }

    private String pgTypeExpr(String type) {
        return switch (type) {
            case "tinyint", "smallint", "mediumint", "int", "integer", "year" -> "integer";
            case "bigint" -> "bigint";
            case "decimal", "numeric" -> "numeric";
            case "float" -> "real";
            case "double" -> "double precision";
            case "tinytext", "text", "mediumtext", "longtext" -> "text";
            case "binary", "varbinary", "blob", "mediumblob", "longblob" -> "bytea";
            case "datetime", "timestamp" -> "timestamp";
            case "date" -> "date";
            case "time" -> "time";
            case "json" -> "jsonb";
            case "bit", "bool", "boolean" -> "boolean";
            case "char" -> "char";
            case "varchar" -> "varchar";
            default -> type;
        };
    }

    private String defaultValueExpr(String type, String rawDefault, boolean pk) {
        if (rawDefault == null || rawDefault.isBlank()) {
            return null;
        }
        String value = rawDefault.trim();
        String upper = value.toUpperCase(Locale.ROOT);
        if ("CURRENT_TIMESTAMP".equals(upper) || "CURRENT_TIMESTAMP()".equals(upper) || "NOW()".equals(upper)) {
            if (!"datetime".equals(type) && !"timestamp".equals(type)) {
                throw new BusinessException(400, "只有 datetime/timestamp 字段可以使用 CURRENT_TIMESTAMP 默认值");
            }
            return "CURRENT_TIMESTAMP";
        }
        if ("NULL".equals(upper)) {
            if (pk) {
                throw new BusinessException(400, "主键字段不能设置默认值 NULL");
            }
            return "NULL";
        }
        if (NUMERIC_TYPES.contains(type) && value.matches("-?\\d+(\\.\\d+)?")) {
            return value;
        }
        if (("boolean".equals(type) || "bool".equals(type) || "bit".equals(type))
                && ("TRUE".equals(upper) || "FALSE".equals(upper))) {
            return upper;
        }
        return "'" + escape(value) + "'";
    }

    private String quote(String identifier) {
        return "\"" + identifier + "\"";
    }

    private String quoteAll(List<String> identifiers) {
        List<String> quoted = new ArrayList<>();
        for (String identifier : identifiers) {
            quoted.add(quote(identifier));
        }
        return String.join(", ", quoted);
    }

    /** PostgreSQL 标准字符串只转义单引号（standard_conforming_strings=on） */
    private String escape(String value) {
        return value.replace("'", "''");
    }

    /**
     * PG 类型名 --> 内部归一化类型名（MySQL 风格）。
     */
    static String normalizeMetaType(String pgType) {
        if (pgType == null) {
            return "varchar";
        }
        String type = pgType.trim().toLowerCase(Locale.ROOT);
        return switch (type) {
            case "int2", "smallint", "smallserial", "serial2" -> "smallint";
            case "int4", "integer", "int", "serial", "serial4" -> "int";
            case "int8", "bigint", "bigserial", "serial8" -> "bigint";
            case "numeric", "decimal", "money" -> "decimal";
            case "float4", "real" -> "float";
            case "float8", "double precision" -> "double";
            case "bool", "boolean" -> "boolean";
            case "varchar", "character varying", "citext", "uuid" -> "varchar";
            case "bpchar", "char", "character" -> "char";
            case "text" -> "text";
            case "bytea" -> "blob";
            case "date" -> "date";
            case "timestamp", "timestamp without time zone", "timestamp with time zone" -> "timestamp";
            case "time", "time without time zone", "time with time zone" -> "time";
            case "json", "jsonb" -> "json";
            case "bit", "bit varying", "varbit" -> "bit";
            default -> "varchar";
        };
    }

    private boolean isTrue(Object value) {
        if (value instanceof Boolean b) {
            return b;
        }
        if (value instanceof Number n) {
            return n.intValue() == 1;
        }
        return false;
    }
}
